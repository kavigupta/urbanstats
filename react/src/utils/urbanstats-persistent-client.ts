import createClient from 'openapi-fetch'

import { QuizModel } from '../quiz/quiz'

import type { paths } from './urbanstats-persistent-data' // generated by openapi-typescript

// This endpoint answers 401 when Google rejects the access token in the request body, which says
// nothing about whether our own identity headers are good.
const authenticatesSomethingElse = '/juxtastat/associate_email'

// eslint-disable-next-line no-restricted-syntax -- Using the window hostname
const hostname = window.location.hostname

export const persistentClient = createClient<paths>({ baseUrl: hostname === 'urbanstats.org' ? 'https://persistent.urbanstats.org' : `http://${hostname}:54579`, async fetch(input) {
    const response = await globalThis.fetch(input)
    // A 401 here means the server holds a different secure id for our persistent id, so someone
    // else is playing as us. Requests without our identity headers can't tell.
    if (input.headers.has('x-secure-id') && new URL(input.url).pathname !== authenticatesSomethingElse) {
        QuizModel.shared.authenticationError.value = response.status === 401
    }
    return response
} })
